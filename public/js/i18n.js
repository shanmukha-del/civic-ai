let currentLangCode = 'te-IN';

function changeLanguage(langKey) {
  let bcp = 'te-IN';
  const l = (langKey || '').toLowerCase();

  if (l === 'telugu' || l === 'te-in') bcp = 'te-IN';
  else if (l === 'hindi' || l === 'hi-in') bcp = 'hi-IN';
  else if (l === 'bengali' || l === 'bn-in') bcp = 'bn-IN';
  else if (l === 'marathi' || l === 'mr-in') bcp = 'mr-IN';
  else if (l === 'tamil' || l === 'ta-in') bcp = 'ta-IN';
  else if (l === 'gujarati' || l === 'gu-in') bcp = 'gu-IN';
  else if (l === 'kannada' || l === 'kn-in') bcp = 'kn-IN';
  else if (l === 'odia' || l === 'or-in') bcp = 'or-IN';
  else if (l === 'malayalam' || l === 'ml-in') bcp = 'ml-IN';
  else if (l === 'punjabi' || l === 'pa-in') bcp = 'pa-IN';
  else if (l === 'assamese' || l === 'as-in') bcp = 'as-IN';
  else if (l === 'english' || l === 'en-in') bcp = 'en-IN';

  currentLangCode = bcp;
  localStorage.setItem('civic_user_language', langKey);
  localStorage.setItem('civic_user_bcp47', bcp);
  applyTranslations();
}

function applyTranslations() {
  const dict = translations[currentLangCode] || translations['te-IN'];

  Object.keys(dict).forEach(key => {
    const el = document.getElementById(`i18n_${key}`);
    if (el) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = dict[key];
      } else {
        el.textContent = dict[key];
      }
    }
  });
}

function setLanguage(langKey) {
  changeLanguage(langKey);
}

window.setLanguage = setLanguage;
window.changeLanguage = changeLanguage;

document.addEventListener('DOMContentLoaded', () => {
  const savedLang = localStorage.getItem('civic_user_language');
  if (savedLang) {
    changeLanguage(savedLang);
  } else {
    applyTranslations();
  }
});
